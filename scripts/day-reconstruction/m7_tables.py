"""Day reconstruction, milestone 7: TABLES.md and per-cell CSVs from m7/results.json (every cell, no selection).

    python scripts/day-reconstruction/m7_tables.py
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "analysis/output/day-reconstruction/m7"
r = json.loads((OUT / "results.json").read_text())


def f(s, d=1, scale=1.0):
    if not s or s.get("est") is None:
        return "—"
    lo, hi = s["ci"]
    if lo is None:
        return f"{s['est'] * scale:+.{d}f}"
    return f"{s['est'] * scale:+.{d}f} [{lo * scale:+.{d}f}, {hi * scale:+.{d}f}]"


def p(s):
    return "—" if not s or s.get("p") is None else f"{s['p']:.4f}"


# per-cell CSVs
t1rows = []
for c in r["T1"]:
    row = {"instrument": c["instrument"], "family": c["family"], "rung": c["rung"], "category": c["category"],
           "n_forecast_share_eligible": c["n"]["1.0"]["share_eligible"], "n_forecast_U": c["n"]["1.0"]["U"],
           "n_forecast_denominator": c["n"]["1.0"]["denominator"],
           **{f"n_denominator_x{k}": v["denominator"] for k, v in c["n"].items() if k != "1.0"}}
    for pk in ("pooled", "Y1-Y3", "Y4-Y6", "2016-20", "untagged_excluded"):
        for st in ("forecast", "placebo_B2", "delta"):
            s = c[pk][st]
            row[f"{pk}_{st}"] = s["est"]
            row[f"{pk}_{st}_lo"], row[f"{pk}_{st}_hi"] = s["ci"]
        row[f"{pk}_delta_p"] = c[pk]["delta"]["p"]
    row.update({"bh_sig": c["bh_sig"], "period_sign_stable": c["period_sign_stable"],
                "failed_conditions": ";".join(c["failed_conditions"]), "class": c["class"]})
    t1rows.append(row)
pd.DataFrame(t1rows).to_csv(OUT / "t1_cells.csv", index=False)

t2rows = []
for c in r["T2"]:
    row = {"instrument": c["instrument"], "family": c["family"], "rung": c["rung"], "condition": c["condition"], "race": c["race"],
           "in_family": c["in_family"], **{f"n_x{k}": v for k, v in c["n"].items()}, "small_placebo_flag": c["small_placebo_flag"]}
    for pk in ("pooled", "Y1-Y3", "Y4-Y6", "2016-20", "untagged_excluded"):
        P = c[pk]
        for st in ("EV_fc", "EV_pl", "dEV"):
            row[f"{pk}_{st}"] = P[st]["est"]
            row[f"{pk}_{st}_lo"], row[f"{pk}_{st}_hi"] = P[st]["ci"]
        row[f"{pk}_EV_fc_p"] = P["EV_fc"]["p"]
        row[f"{pk}_H"] = P["H"]
    P = c["pooled"]
    for st in ("unresolved_share", "resolved_contribution", "unresolved_contribution", "mean_unresolved_payoff"):
        row[st] = P[st]["est"]
        row[f"{st}_lo"], row[f"{st}_hi"] = P[st]["ci"]
    row["D2_EV_fc"] = P["D2_U_excluded"]["EV_fc"]["est"]
    row["D2_dEV"] = P["D2_U_excluded"]["dEV"]["est"]
    row["breakeven_share"] = P["breakeven_share"]
    row.update({"bh_sig": c.get("bh_sig"), **{f"cond_{k}": v for k, v in c["conditions"].items()}, "class": c["class"]})
    t2rows.append(row)
pd.DataFrame(t2rows).to_csv(OUT / "t2_cells.csv", index=False)

L = ["# M7 tables (generated by scripts/day-reconstruction/m7_tables.py from results.json)", "",
     f"B = {r['meta']['B']}, seed {r['meta']['seed']}; prereg frozen {r['meta']['frozen']}, rules {r['meta']['rules']}. "
     "95% percentile intervals, paired date Poisson bootstrap. Point-in-time era 2020-08-21 to 2026-08-20 unless marked. "
     "Placebo = B2-weighted phantom ladders (x0.70/0.85/1.15/1.30, w = -1/6, 2/3, 2/3, -1/6). Full numeric columns: t1_cells.csv, t2_cells.csv.", ""]

L += ["## Build-time checks", "", "```", json.dumps(r["checks"], indent=1, default=str), "```", ""]

L += ["## Counts and gaps (point-in-time; forecast and each factor)", "",
      "| cell | line set | share-eligible | EV-eligible | U (gap / no gap) | 1 | 2 | 3 | 4a | 4b | 5a | 5b | gap-resolved | gap σ median / max |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for key, cc in r["counts"].items():
    for fs, x in cc.items():
        cat = x["categories"]
        gm = "—" if x["gap_sigma_median"] is None else f"{x['gap_sigma_median']:.3f} / {x['gap_sigma_max']:.3f}"
        L.append(f"| {key} | x{fs} | {x['share_eligible']} | {x['ev_eligible']} | {x['U']} ({x['U_gap']} / {x['U_no_gap']}) | "
                 + " | ".join(str(cat.get(k, 0)) for k in ("1", "2", "3", "4a", "4b", "5a", "5b")) + f" | {x['gap_resolved']} | {gm} |")

L += ["", "## T1. Category shares, forecast vs B2 placebo (78 cells, one BH family q < 0.10), pp", "",
      "Share denominator = share-eligible minus U. Period columns are Δ point estimates.", "",
      "| cell | cat | denom fc | forecast % | placebo % | Δ pp [95%] | p | BH | Y1-Y3 Δ | Y4-Y6 Δ | 2016-20 Δ | untagged-excl Δ | class |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for c in r["T1"]:
    P = c["pooled"]
    fl = f" (failed: {', '.join(c['failed_conditions'])})" if c["class"].startswith("Inconclusive") else ""
    L.append(f"| {c['instrument']} {c['family']} {c['rung']} | {c['category']} | {c['n']['1.0']['denominator']} | "
             f"{P['forecast']['est']:.1f} | {P['placebo_B2']['est']:.1f} | {f(P['delta'])} | {p(P['delta'])} | {'yes' if c['bh_sig'] else 'no'} | "
             f"{c['Y1-Y3']['delta']['est']:+.1f} | {c['Y4-Y6']['delta']['est']:+.1f} | {c['2016-20']['delta']['est']:+.1f} | "
             f"{c['untagged_excluded']['delta']['est']:+.1f} | {c['class']}{fl} |")

L += ["", "## T2. Reference-race EV by condition (R), forecast vs B2 placebo", "",
      "EV is a behavioural reference-race statistic, not a strategy return. H = cost hurdle (materiality bar). "
      "In-family cells form one BH family (q < 0.10) on EV_fc's p. Period columns: EV_fc / ΔEV point estimates.", "",
      "| cell | condition | race | n fc | fam | EV_fc [95%] | p | EV_pl | ΔEV [95%] | H | unres % | unres contrib | D2 EV_fc | Y1-Y3 | Y4-Y6 | 2016-20 | untag-excl EV_fc | small ph | class |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for c in r["T2"]:
    P = c["pooled"]
    per = " | ".join(f"{(c[k]['EV_fc']['est'] or 0):+.3f} / {(c[k]['dEV']['est'] or 0):+.3f}" for k in ("Y1-Y3", "Y4-Y6", "2016-20"))
    L.append(f"| {c['instrument']} {c['family']} {c['rung']} | {c['condition']} | {c['race']} | {c['n']['1.0']} | {'in' if c['in_family'] else 'desc'} | "
             f"{f(P['EV_fc'], 3)} | {p(P['EV_fc'])} | {f({'est': P['EV_pl']['est'], 'ci': [None, None]}, 3)} | {f(P['dEV'], 3)} | "
             f"{P['H']:.3f} | {P['unresolved_share']['est']:.0f} | {P['unresolved_contribution']['est']:+.3f} | {P['D2_U_excluded']['EV_fc']['est']:+.3f} | "
             f"{per} | {(c['untagged_excluded']['EV_fc']['est'] or 0):+.3f} | {'yes' if c['small_placebo_flag'] else ''} | {c['class']} |")

L += ["", "## Within-category distributions (point-in-time, medians; forecast vs B2 placebo)", "",
      "σ for distances, minutes for times. Quartiles, 90th percentiles and intervals in results.json.", "",
      "| cell | cat | n fc | further travel | retrace | t to N | t to P | t to O | MAE cont | MFE cont | MAE fade | MFE fade |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for key, dd in r["distributions"].items():
    for c, ms in dd.items():
        if c.startswith("_"):
            continue
        n = max((v["n_forecast"] for v in ms.values()), default=0)
        cells = []
        for mk in ("further_travel", "retrace_depth", "t_N", "t_P", "t_O", "MAE_C", "MFE_C", "MAE_F", "MFE_F"):
            if mk not in ms:
                cells.append("—"); continue
            q = ms[mk]["q50"]
            d = 0 if mk.startswith("t_") else 2
            fe, pe = q["forecast"]["est"], q["placebo_B2"]["est"]
            cells.append(f"{fe:.{d}f} ({pe:.{d}f})" if pe is not None else f"{fe:.{d}f}")
        L.append(f"| {key} | {c} | {n} | " + " | ".join(cells) + " |")

L += ["", "## Excursions by race outcome (forecast, point-in-time, medians in σ)", "",
      "| cell | race | outcome | n | MAE median | MFE median |", "|---|---|---|---|---|---|"]
for key, dd in r["distributions"].items():
    for race, oc in dd["_race_outcome_excursions"].items():
        for o_, v in oc.items():
            if v["n"]:
                L.append(f"| {key} | {race} | {o_} | {v['n']} | {v['MAE_median']:.3f} | {v['MFE_median']:.3f} |")

(OUT / "TABLES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote", len(L), "lines")
