"""Day reconstruction, milestone 6: TABLES.md from m6/results.json (every pre-registered cell, no selection).

    python scripts/day-reconstruction/m6_tables.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "analysis/output/day-reconstruction/m6"
r = json.loads((OUT / "results.json").read_text())
A, Bp, C = r["A"], r["B"], r["C"]


def f(s, d=1, sign=True):
    fmt = f"{{:{'+' if sign else ''}.{d}f}}"
    return f"{fmt.format(s['est'])} [{fmt.format(s['ci'][0])}, {fmt.format(s['ci'][1])}]"


L = ["# M6 tables (generated by scripts/day-reconstruction/m6_tables.py from results.json)", "",
     f"B = {r['meta']['B']}, seed {r['meta']['seed']}, frozen prereg commit {r['meta']['frozen_commit']}. "
     "Intervals are 95% percentile; Part A uses the paired date Poisson bootstrap (block bootstrap as sensitivity); "
     "Parts B and C use the 20-session moving-block bootstrap except B6 (paired date bootstrap).", ""]

L += ["## A8. Out-of-sample skill, test Y3-Y6 pooled (12 primary comparisons, BH q < 0.10)", "",
      "| cell | comparison | n test | log-loss skill % | Brier skill % | p | BH | class (Poisson) | class (block) | final | untagged excluded | 2016-20 skill % |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for k, c in A["cells"].items():
    for comp in ("M1_vs_M0", "M2_vs_M1"):
        x = c[comp]
        L.append(f"| {k} | {comp} | {c['n_test']} | {f(x['logloss_skill'], 2)} | {f(x['brier_skill'], 2)} | {x['logloss_skill']['p']:.4f} | "
                 f"{'yes' if x['bh_sig'] else 'no'} | {x['class_poisson']} | {x['class_block']} | **{x['class']}** | "
                 f"{x['class_untagged_excluded']}{' (NOT ROBUST)' if x['not_robust_to_untagged'] else ''} | {f(x['is_2016_20'], 2)} |")
L += ["", "### A8 by test year (log-loss skill %)", "", "| cell | comparison | Y3 | Y4 | Y5 | Y6 |", "|---|---|---|---|---|---|"]
for k, c in A["cells"].items():
    for comp in ("M1_vs_M0", "M2_vs_M1"):
        by = c[comp]["by_year"]
        L.append(f"| {k} | {comp} | " + " | ".join(f(by[str(y)]['logloss_skill'], 2) if str(y) in by else "—" for y in (3, 4, 5, 6)) + " |")

L += ["", "## A9. Calibration-in-the-large (mean predicted - observed, pp), pooled Y3-Y6", "",
      "| cell | working model | CITL pp | class (Poisson / block) | final | untagged excluded | slope | ECE pp (noise mean / p95) | AUC | M0 CITL | M1 CITL | M2 CITL |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for k, c in A["cells"].items():
    a = c["A9"]
    L.append(f"| {k} | {a['working_model']} | {f(a['citl'])} | {a['class_poisson']} / {a['class_block']} | **{a['class']}** | "
             f"{a['class_untagged_excluded']}{' (NOT ROBUST)' if a['not_robust_to_untagged'] else ''} | {f(a['slope'], 2, False)} | "
             f"{a['ece_pp']['est']:.1f} ({a['ece_pp']['noise_floor_mean']:.1f} / {a['ece_pp']['noise_floor_p95']:.1f}) | {a['auc']:.3f} | "
             f"{f(c['citl']['M0'])} | {f(c['citl']['M1'])} | {f(c['citl']['M2'])} |")
L += ["", "### A9 reliability (working model, quintiles of predicted reach, pooled Y3-Y6)", "",
      "| cell | bin | n | predicted % | observed % |", "|---|---|---|---|---|"]
for k, c in A["cells"].items():
    for b in c["A9"]["reliability"]:
        L.append(f"| {k} | {b['bin']} | {b['n']} | {f(b['pred'], 1, False)} | {f(b['obs'], 1, False)} |")
L += ["", "### A9 CITL by test year (working model) and by side", "",
      "| cell | Y3 | Y4 | Y5 | Y6 | up | down |", "|---|---|---|---|---|---|---|"]
for k, c in A["cells"].items():
    wm = c["A9"]["working_model"]
    by = c["citl"][wm]["by_year"]
    L.append(f"| {k} | " + " | ".join(f(by[str(y)]) for y in (3, 4, 5, 6)) + f" | {f(c['citl_by_side']['up'][wm])} | {f(c['citl_by_side']['dn'][wm])} |")
L += ["", "### Q1. M0 predicted next-rung reach by clock time (fit on Y1-Y5), %", "",
      "| cell | rung | 08:00 | 12:00 | 16:00 | 20:00 |", "|---|---|---|---|---|---|"]
for k, c in A["cells"].items():
    q = c["Q1_M0_at_clock"]
    for ru in ("p50", "p75"):
        L.append(f"| {k} | {ru} | " + " | ".join(f(q[f'{h}|{ru}'], 1, False) for h in ("08:00", "12:00", "16:00", "20:00")) + " |")

L += ["", "## A10. Forecast vs placebo next-rung reach (6 cells, second BH family), pooled Y3-Y6, pp", "",
      "| cell | n fc / ph 0.70, 0.85, 1.15, 1.30 | observed fc % | G predicted fc % | fc residual | B2 placebo residual | Δ_adj | p | BH | class (Poisson / block) | final | untagged excluded | 2016-20 Δ_adj |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for k, c in A["cells"].items():
    a = c["A10"]
    n = a["n_test"]
    L.append(f"| {k} | {n['1.0']} / {n['0.7']}, {n['0.85']}, {n['1.15']}, {n['1.3']} | {f(a['obs_fc'], 1, False)} | {f(a['G_pred_fc'], 1, False)} | "
             f"{f(a['fc_resid'])} | {f(a['pl_resid_B2'])} | {f(a['delta_adj'])} | {a['delta_adj']['p']:.4f} | {'yes' if a['bh_sig'] else 'no'} | "
             f"{a['class_poisson']} / {a['class_block']} | **{a['class']}** | {a['class_untagged_excluded']}{' (NOT ROBUST)' if a['not_robust_to_untagged'] else ''} | "
             f"{a['sign_2016_20']:+.1f} |")
L += ["", "### A10 descriptive splits (Δ_adj, pp)", "", "| cell | p50 | p75 | up | down | Y3 | Y4 | Y5 | Y6 |", "|---|---|---|---|---|---|---|---|---|"]
for k, c in A["cells"].items():
    L.append(f"| {k} | {f(c['A10_by_rung']['p50'])} | {f(c['A10_by_rung']['p75'])} | {f(c['A10_by_side']['up'])} | {f(c['A10_by_side']['dn'])} | "
             + " | ".join(f(c['A10_by_year'][str(y)]) for y in (3, 4, 5, 6)) + " |")
L += ["", "### A11. Exclusions (forecast p50/p75 first touches)", "", "```", json.dumps(A["exclusions"], indent=1), "```"]

L += ["", "## B1. p90 boundary frequency, point-in-time days (%)", "",
      "| instrument | event | rate [block 95%] | iid 95% | class | untagged excluded | Y1-Y3 | Y4-Y6 | 2016-20 |", "|---|---|---|---|---|---|---|---|---|"]
for nm, b in Bp["B1"].items():
    for ev in ("fixed_up", "fixed_dn", "fixed_either", "fixed_both", "proj_hl", "proj_p90_touched_either"):
        x = b[ev]
        h = x["halves"]
        ut = x.get("untagged_excluded")
        L.append(f"| {nm} ({b['n_days']} days) | {ev} | {f(x, 1, False)} | [{x['ci_iid'][0]:.1f}, {x['ci_iid'][1]:.1f}] | {x.get('class', '—')} | "
                 f"{(f(ut, 1, False) + ' ' + ut['class']) if ut else '—'} | {f(h['Y1-Y3'], 1, False)} | {f(h['Y4-Y6'], 1, False)} | "
                 f"{f(h['2016-20'], 1, False) if '2016-20' in h else '—'} |")
L += ["", "## B2. p90 overshoot O (sigma beyond the level, to 22:00)", "", "### Unconditional (every day x side; O_day = 0 if p90 not reached)", "",
      "| cell | side | n | P(not reached) % | P(O_day >= 0.10) % | >= 0.25 | >= 0.50 | >= 1.00 | mean O_day σ |", "|---|---|---|---|---|---|---|---|---|"]
for k, b in Bp["B2"].items():
    for sd, u in b["unconditional"].items():
        L.append(f"| {k} | {sd} | {u['n_day_sides']} | {f(u['P_not_reached'], 1, False)} | {f(u['P_O_day_ge_0.10'], 1, False)} | {f(u['P_O_day_ge_0.25'], 1, False)} | "
                 f"{f(u['P_O_day_ge_0.50'], 1, False)} | {f(u['P_O_day_ge_1.00'], 1, False)} | {f(u['mean_O_day'], 3, False)} |")
L += ["", "### Conditional (per p90 first touch)", "",
      "| cell | side | n | median σ | p75 σ | p90 σ | mean σ | contained < 0.10σ % | between % | extended ≥ 0.25σ % | P(O ≥ p90-p75 step) % |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for k, b in Bp["B2"].items():
    for sd, c in b["conditional"].items():
        st = f(Bp["B3"][k]["P_O_ge_step"], 1, False) if sd == "pooled" else ""
        L.append(f"| {k} | {sd} | {c['n']} | {f(c['median'], 2, False)} | {f(c['p75'], 2, False)} | {f(c['p90'], 2, False)} | {f(c['mean'], 2, False)} | "
                 f"{f(c['P_contained_lt_0.10'], 1, False)} | {f(c['P_between'], 1, False)} | {f(c['P_extended_ge_0.25'], 1, False)} | {st} |")
for part, lab, a_, b_ in (("B4", "time (first = more time left than the median touch)", "early", "late"),
                          ("B5", "range used, fixed only (first = u at or below the median)", "low u", "high u")):
    L += ["", f"## {part}. Overshoot split by {lab}", "",
          f"| cell | measure | n {a_} / {b_} | P(extended) {a_} | {b_} | diff pp | P(contained) {a_} | {b_} | diff pp | median {a_} σ | {b_} | diff |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, b in Bp[part].items():
        if "not_estimable" in b:
            L.append(f"| {k} | not estimable (u pinned): u 10/50/90% = {', '.join(f'{x:.2f}' for x in b['u_quantiles_10_50_90'])}, n = {b['n']} | | | | | | | | | | |")
            continue
        for col in ("O", "O120"):
            x = b[col]
            L.append(f"| {k} | {col} | {x['n_first']} / {x['n_second']} | {f(x['P_extended_first'], 1, False)} | {f(x['P_extended_second'], 1, False)} | {f(x['diff_P_extended'])} | "
                     f"{f(x['P_contained_first'], 1, False)} | {f(x['P_contained_second'], 1, False)} | {f(x['diff_P_contained'])} | "
                     f"{f(x['median_first'], 2, False)} | {f(x['median_second'], 2, False)} | {f(x['diff_median'], 2)} |")
L += ["", "## B6. p90 boundary vs B2-weighted phantom p90 (descriptive, paired date bootstrap), %", "",
      "| cell | horizon | n fc / 0.70, 0.85, 1.15, 1.30 | contained fc | contained ref | diff | extended fc | extended ref | diff |", "|---|---|---|---|---|---|---|---|---|"]
for k, b in Bp["B6"].items():
    for hz, x in b.items():
        n = x["n"]
        L.append(f"| {k} | {hz} | {n['1.0']} / {n['0.7']}, {n['0.85']}, {n['1.15']}, {n['1.3']} | {f(x['contained']['forecast'], 1, False)} | "
                 f"{f(x['contained']['B2_reference'], 1, False)} | {f(x['contained']['diff'])} | {f(x['extended']['forecast'], 1, False)} | "
                 f"{f(x['extended']['B2_reference'], 1, False)} | {f(x['extended']['diff'])} |")

L += ["", "## C. First-touch timing (London clock)", "",
      "Window shares are of touched days; F(end) is the share of all days touched by the session end. Reference = B2-weighted phantom ladders.", "",
      "| instrument | era | family | rung | side | days | touched | F(end) % | median clock (ref, diff h) | 00-08 % (diff) | 08-13:30 % (diff) | 13:30-17 % (diff) | 17-22 % (diff) |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]


def clock(h):
    return f"{int(h):02d}:{int(round((h % 1) * 60)) % 60:02d}"


for k, c in C.items():
    nm, era, grp, ru, sd = k.split("|")
    m = c["m"]
    if "clock_q50" not in m:
        continue
    med = m["clock_q50"]
    cells = []
    for wn in ("00:00-08:00", "08:00-13:30", "13:30-17:00", "17:00-22:00"):
        x = m[f"share_touched|{wn}"]
        cells.append(f"{x['forecast']['est']:.0f} ({x['diff']['est']:+.1f} [{x['diff']['ci'][0]:+.1f}, {x['diff']['ci'][1]:+.1f}])" if "diff" in x else f"{x['forecast']['est']:.0f}")
    md = f"{clock(med['forecast']['est'])} ({clock(med['reference_B2']['est'])}, {med['diff']['est']:+.2f} [{med['diff']['ci'][0]:+.2f}, {med['diff']['ci'][1]:+.2f}])" if "diff" in med else clock(med['forecast']['est'])
    L.append(f"| {nm} | {era} | {grp} | {ru} | {sd} | {c['n_days']} | {c['n_touched']} | {m['F_end']['forecast']['est']:.1f} | {md} | " + " | ".join(cells) + " |")

L += ["", "### C by year (point-in-time, pooled sides): median clock and window shares of touched days", "",
      "| instrument | family | rung | " + " | ".join(f"Y{y}" for y in range(1, 7)) + " |", "|---|---|---|" + "---|" * 6]
for k, c in C.items():
    nm, era, grp, ru, sd = k.split("|")
    if era != "pit" or sd != "pooled" or "by_year" not in c:
        continue
    cells = []
    for y in range(1, 7):
        b = c["by_year"][f"Y{y}"]
        if "clock_q50" not in b:
            cells.append("—"); continue
        cells.append(f"{clock(b['clock_q50']['est'])} n={b['n_touched']} | ".rstrip(" |") + " (" + "/".join(f"{b[f'share_touched|{wn}']['est']:.0f}" for wn in ("00:00-08:00", "08:00-13:30", "13:30-17:00", "17:00-22:00")) + ")")
    L.append(f"| {nm} | {grp} | {ru} | " + " | ".join(cells) + " |")

(OUT / "TABLES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote", OUT / "TABLES.md", len(L), "lines")
