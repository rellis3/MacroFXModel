"""Freeze the Phase 2 M1 reach model (forge/LEVEL_P2_PREREG.md, fit < 2022) for the S3 scenario shadow (forge/LEVEL_SCENARIO_SHADOW_PREREG.md).

    PYTHONPATH=. python scripts/levels/export_reach_params.py

Refits M1 exactly as p2_eval.py does (same design, same 600k subsample size of the fit block; the subsample seed differs, so
coefficients match p2_eval to sampling noise) and writes:
  js/levelReachParams.js                         frozen coefficients + scaler + class vol-time hour shares
  analysis/output/level_p2/reach_parity.json     400 E-conf rows with Python predictions (JS parity test fixture)
  analysis/output/level_p2/reach_export_check.json  skill vs B1 of the frozen model on E-dev / E-conf (must match RESULTS.md)
"""
from __future__ import annotations

import hashlib
import json
from math import erf, sqrt
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler

IN = Path("data/levels/p2")
OUT = Path("analysis/output/level_p2")
JS = Path("js/levelReachParams.js")
FIT_END, CONF0, CONF1 = "2022-01-01", "2025-01-01", "2026-08-21"
HZ = {"30": "v05", "60": "v1", "120": "v2", "240": "v4", "end": "vend"}
MINS = {"30": 30, "60": 60, "120": 120, "240": 240, "end": None}
HOURS, CLASSES = [3, 7, 10, 13, 16], ["cross", "gold", "index", "major"]
PROF = json.loads(Path("analysis/output/intraday_extreme_paths/discovery_profile.json").read_text())["share"]
rng = np.random.default_rng(20261011)
phi = np.vectorize(lambda x: 0.5 * (1 + erf(x / sqrt(2))))


def design(z, v, used, ext, h, cls):
    cols = [z, np.log(np.clip(z, 1e-3, None)), np.log(np.clip(v, 1e-4, None)), used, ext.astype(float)]
    cols += [(h == k).astype(float) for k in HOURS] + [(cls == k).astype(float) for k in CLASSES]
    return np.column_stack(cols)


FEATS = ["z", "lz", "lv", "used", "ext"] + [f"h_{k}" for k in HOURS] + [f"c_{k}" for k in CLASSES]

L = pd.concat([pd.read_parquet(f, columns=["date", "h", "dist", "t_min", "used", "D", "oos", "v05", "v1", "v2", "v4", "vend", "cls"])
               for f in sorted(IN.glob("*_levels.parquet"))], ignore_index=True)
L = L[L.date < CONF1]
L = L[(L.date < FIT_END) | (L.oos == 1)].reset_index(drop=True)
blk = np.select([L.date < FIT_END, L.date < CONF0], ["fit", "dev"], "conf")
d = L.dist.abs().to_numpy()
ext = np.sign(L.dist.to_numpy()) == np.sign(L.D.to_numpy())
h, cls, used = L.h.to_numpy(), L.cls.to_numpy(), L.used.to_numpy()
fit_i = np.flatnonzero(blk == "fit")
fit_i = np.sort(rng.choice(fit_i, 600_000, replace=False))
models, check = {}, {}
par_i = np.sort(rng.choice(np.flatnonzero(blk == "conf"), 400, replace=False))
parity = {"rows": []}
for hz, vc in HZ.items():
    v = L[vc].to_numpy()
    z = d / np.sqrt(np.clip(v, 1e-6, None))
    X = design(z, v, used, ext, h, cls)
    y = (L.t_min.notna() & ((L.t_min < MINS[hz]) if MINS[hz] else True)).to_numpy().astype(float)
    sc = StandardScaler().fit(X[fit_i])
    m = LogisticRegression(C=1.0, max_iter=2000).fit(sc.transform(X[fit_i]), y[fit_i])
    # fold the scaler into raw-feature coefficients: logit = b0 + sum(w_j * x_j)
    w = m.coef_[0] / sc.scale_
    b0 = float(m.intercept_[0] - np.sum(m.coef_[0] * sc.mean_ / sc.scale_))
    models[hz] = {"intercept": round(b0, 10), "coef": {f: round(float(c), 10) for f, c in zip(FEATS, w)}}
    p = 1 / (1 + np.exp(-(b0 + X @ w)))
    b1 = np.clip(2 * (1 - phi(z)), 1e-4, 1 - 1e-4)
    check[hz] = {b: round(100 * (1 - np.sum((p[blk == b] - y[blk == b]) ** 2) / np.sum((b1[blk == b] - y[blk == b]) ** 2)), 2) for b in ("dev", "conf")}
    for k, i in enumerate(par_i):
        if hz == "30":
            parity["rows"].append({"dist": float(d[i]), "used": float(used[i]), "ext": bool(ext[i]), "h": int(h[i]), "cls": str(cls[i]), "v": {}, "p": {}})
        parity["rows"][k]["v"][hz] = float(v[i])
        parity["rows"][k]["p"][hz] = float(p[i])
    print(hz, check[hz], flush=True)

shares = {c: [round(PROF[c].get(f"{hr}|1", 0.0), 8) for hr in range(24)] for c in CLASSES}
body = {"model": "level reach M1 (LEVEL_P2), fit < 2022-01-01", "prereg": "forge/LEVEL_SCENARIO_SHADOW_PREREG.md",
        "hours_fitted": HOURS, "classes": CLASSES, "features": FEATS, "horizons": models, "hour_shares": shares,
        "domain": {"dist_sigma": [0.05, 3.0]}}
blob = json.dumps(body, sort_keys=True)
ver = hashlib.sha256(blob.encode()).hexdigest()[:16]
JS.write_text("// GENERATED by scripts/levels/export_reach_params.py - do not edit. Frozen for the S3 scenario shadow.\n"
              f"export const REACH_MODEL_VERSION = '{ver}';\nexport const REACH_PARAMS = {blob};\n", encoding="utf-8")
(OUT / "reach_parity.json").write_text(json.dumps(parity))
(OUT / "reach_export_check.json").write_text(json.dumps({"version": ver, "skill_vs_B1_pct": check}, indent=1))
print("version", ver)
