"""Out-of-sample reliability of the project's chosen lines, for the "Project output" export (js/projectOutputEvidence.js).

    python scripts/forecast_history/export_project_output_evidence.py

Daily: the chosen ladder (persistence + IV where implied vol exists, persistence elsewhere), rebuilt point-in-time in
VF3 Stage B (analysis/output/vf3_stage_b/part1_lines.parquet, oos rows 2020-08 -> 2026-08-20): per instrument and rung, the
share of sessions the line was reached (O->H / O->L) or exceeded (H-L).
Weekly: Forecast Weekly - Reverting (forge/HORIZON_REVERSION_PREREG.md test windows): H-L p50 / p75 exceedance.
Also the daily-vs-weekly descriptive comparison (analysis/output/daily_vs_weekly/summary.json). Nothing is fitted here.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

OUT = Path("js/projectOutputEvidence.js")
LIVE = {"SPX": "SPX500", "DOW": "US30"}
d = pd.read_parquet("analysis/output/vf3_stage_b/part1_lines.parquet")
d = d[d.oos == 1]
daily = {}
for inst, g in d.groupby("inst"):
    arm = "SI" if g["SI_hl_p50"].notna().mean() > 0.5 else "S"
    g = g[g[f"{arm}_hl_p50"].notna()]
    rec = {"arm": "persistence + IV" if arm == "SI" else "persistence", "n": int(len(g)), "from": str(g.date.min()), "to": str(g.date.max())}
    for t in ("oh", "ol", "hl"):
        for p in ("p50", "p75", "p90"):
            ok = g[f"r_{t}"].notna() & g[f"{arm}_{t}_{p}"].notna()
            rec[f"{t}_{p}"] = round(float((g.loc[ok, f"r_{t}"] >= g.loc[ok, f"{arm}_{t}_{p}"]).mean()), 3)
    daily[LIVE.get(inst, inst)] = rec
hr = json.loads(Path("analysis/output/horizon_reversion/results.json").read_text())["horizons"]["weekly"]
weekly = {}
for r in hr["per_instrument"]:
    weekly[LIVE.get(r["inst"], r["inst"])] = {"n_test": r["n_test"], "hl_p50": r["B_exc50"], "hl_p75": r["B_exc75"]}
dvw = json.loads(Path("analysis/output/daily_vs_weekly/summary.json").read_text())
body = {"generated": "2026-10-11", "daily": daily, "weekly": weekly, "daily_vs_weekly": dvw,
        "sources": {"daily": "analysis/output/vf3_stage_b (Stage B part 1, point-in-time, oos rows)",
                    "weekly": "analysis/output/horizon_reversion/RESULTS.md (test windows)",
                    "daily_vs_weekly": "forge/daily_vs_weekly_descriptive.py (descriptive)"}}
OUT.write_text("// GENERATED by scripts/forecast_history/export_project_output_evidence.py - do not edit.\n"
               f"export const PROJECT_OUTPUT_EVIDENCE = {json.dumps(body, sort_keys=True)};\n", encoding="utf-8")
print(len(daily), "daily,", len(weekly), "weekly")
print(pd.DataFrame(daily).T[["arm", "n", "oh_p50", "oh_p75", "oh_p90", "hl_p50", "hl_p75", "hl_p90"]].to_string())
