// Turns analysis/output/reach_calibration/curves.json into js/oiReachCalibData.js (the curves js/oiReachability.js applies).
//   per instrument & horizon: use the instrument's OWN curve when it beats its asset-class curve out of sample by >= 0.3pp,
//   otherwise the asset-class curve (more data, less noise). Each entry carries the OOS error it was measured at.
//   node analysis/reach_calibration_emit.mjs
import fs from 'fs';
const R = JSON.parse(fs.readFileSync('analysis/output/reach_calibration/curves.json', 'utf8'));
const out = { generated: R.generated, window: R.window, split: R.split, instruments: {}, classes: {}, pooled: {} };
for (const [H, h] of Object.entries(R.horizons)) {
  out.pooled[H] = { curve: h.pooled.curve };
  for (const [c, v] of Object.entries(h.classes)) (out.classes[c] ||= {})[H] = { curve: v.curve, members: v.members };
  for (const [k, v] of Object.entries(h.instruments)) {
    const own = v.oos.ownCurve, cl = v.oos.assetClass; if (!own || !cl) continue;
    const useOwn = own.eceP + 0.3 <= cl.eceP;
    (out.instruments[k] ||= {})[H] = { curve: useOwn ? v.curve : h.classes[Object.keys(h.classes).find(c => h.classes[c].members.includes(k))].curve,
      source: useOwn ? 'own' : 'class', oosErrPp: useOwn ? own.eceP : cl.eceP, worstBinPp: useOwn ? own.worstBinP : cl.worstBinP, testN: v.testN };
  }
}
const js = `// GENERATED by analysis/reach_calibration_emit.mjs from analysis/output/reach_calibration/curves.json — do not edit by hand.
// Touch-probability reliability curves fitted PER INSTRUMENT and PER HORIZON on M5 history ${R.window}
// (${R.split}). Targets span 0.02-3 sigma from price, including the near-price region the original EUR/USD-only fit never saw.
// Entry shape: instruments[key][horizonBars] = { curve: [[rawP, realisedP], ...], source: 'own'|'class', oosErrPp, worstBinPp, testN }
export const REACH_CALIB_DATA = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync('js/oiReachCalibData.js', js);
console.log('wrote js/oiReachCalibData.js', Object.keys(out.instruments).length, 'instruments');
for (const [k, v] of Object.entries(out.instruments)) console.log(k.padEnd(8), Object.entries(v).map(([H, e]) => `${H}:${e.source} ${e.oosErrPp}pp (worst ${e.worstBinPp})`).join(' | '));
