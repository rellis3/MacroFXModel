// Theory Lab practice index: every lesson's scenario drill in one file, for the mixed daily drill (practice.html).
//   node js/buildPracticeIndex.mjs          rebuild theory-lab/assets/practice-data.js, lesson-index.js (+ practice-admin.js)
//   node js/buildPracticeIndex.mjs --check  fail if either file is out of date (CI)
// Public lessons go in practice-data.js. Drills from admin-only lessons (action-*, institutional-*) go in
// practice-admin.js, which the server serves to the education admin only (like paths-admin.js).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'theory-lab');
const dir = path.join(root, 'lessons');
const pub = [], adm = [], lpub = {}, ladm = {};
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.html') && !f.includes('-micro')).sort()) {
  const s = fs.readFileSync(path.join(dir, f), 'utf8'), slug = f.slice(0, -5);
  const admin = /^(action|institutional)-/.test(slug);
  const h1 = ((s.match(/<h1 class="tl-title">([\s\S]*?)<\/h1>/) || [])[1] || slug).replace(/<[^>]+>/g, '').trim();
  // Self-test size as a non-admin reader sees it, so practice.html can say "mastered" without fetching the lesson.
  const seen = admin ? s : s.replace(/<!-- DESK:START -->[\s\S]*?<!-- DESK:END -->/g, '');
  (admin ? ladm : lpub)[slug] = { t: h1, q: (seen.match(/<details class="tl-quiz"/g) || []).length };
  const m = s.match(/<div class="tl-drill"[\s\S]*?<div class="tl-drill-outcome">[\s\S]*?<\/div>\s*<\/div>/);
  if (!m) continue;
  const drill = m[0].replace(/<!-- DESK:START -->[\s\S]*?<!-- DESK:END -->/g, '').replace(/\n\s*/g, ' ');
  const date = (drill.match(/data-date="([^"]+)"/) || [])[1] || null;
  (admin ? adm : pub).push({ slug, title: h1, date, html: drill });
}
const head = '/* Generated by js/buildPracticeIndex.mjs from the lessons\' own drills. Do not edit by hand. */\n';
const out = {
  'practice-data.js': head + 'window.TL_DRILLS = ' + JSON.stringify(pub) + ';\n',
  // Small on purpose: paths.html and practice.html load it for titles and self-test sizes ("mastered" needs both).
  'lesson-index.js': head + 'window.TL_LESSONS = ' + JSON.stringify(lpub) + ';\n',
  'practice-admin.js': head + '(window.TL_DRILLS = window.TL_DRILLS || []).push.apply(window.TL_DRILLS, ' + JSON.stringify(adm) + ');\n' +
    'Object.assign(window.TL_LESSONS = window.TL_LESSONS || {}, ' + JSON.stringify(ladm) + ');\n',
};
const check = process.argv.includes('--check'); let bad = 0;
// lesson-index.js: { slug: { t: title, q: self-test questions } } for every public lesson; admin lessons are added by practice-admin.js.
for (const [name, txt] of Object.entries(out)) {
  const p = path.join(root, 'assets', name);
  if (check) { const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : ''; if (cur !== txt) { console.log(`  ✗ FAIL ${name} is out of date: run node js/buildPracticeIndex.mjs`); bad++; } }
  else fs.writeFileSync(p, txt);
}
console.log(`  ${pub.length} public drills, ${adm.length} admin drills` + (check ? (bad ? `\n\n${bad} FAILED` : '\n\nall passed') : ' written'));
process.exit(bad ? 1 : 0);
