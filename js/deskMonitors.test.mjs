// node js/deskMonitors.test.mjs: the server half of monitors (save, delete, caps, who may call).
import assert from 'node:assert/strict';
import { applyAction, handle, readStore, KEY } from './deskMonitors.js';
import { MAX_LISTS, MAX_ITEMS } from './terminal/monitorCore.js';
const mem = () => { const m = new Map(); return { m, get: async k => m.get(k) ?? null, put: async (k, v) => { m.set(k, v); } }; };
let n = 0; const ok = (c, m) => { assert.ok(c, m); n++; };
const s = { v: 1, lists: [] };
let r = applyAction(s, { action: 'save', name: 'Mine', items: ['eurusd', 'NQ', 'nope', 'EURUSD'] });
ok(r.ok && r.store.lists[0].items.join() === 'EURUSD,NQ', 'save keeps known markets, upper-cased, no repeats');
r = applyAction(r.store, { action: 'save', name: 'mine', items: ['GOLD'] });
ok(r.ok && r.store.lists.length === 1 && r.store.lists[0].items[0] === 'GOLD', 'same name in any case replaces');
ok(!applyAction(s, { action: 'save', name: 'FX majors', items: ['GOLD'] }).ok, 'a starter name is refused');
ok(!applyAction(s, { action: 'save', name: 'Empty', items: ['zzz'] }).ok, 'nothing known = nothing to save');
ok(applyAction(r.store, { action: 'delete', name: 'MINE' }).store.lists.length === 0, 'delete');
ok(applyAction(r.store, { action: 'delete', name: 'zzz' }).status === 404, 'delete missing = 404');
ok(applyAction(s, { action: 'wipe', name: 'x' }).status === 400 && applyAction(s, { action: 'save', name: ' ' }).status === 400, 'bad action / no name');
let big = s;
for (let i = 0; i < MAX_LISTS; i++) big = applyAction(big, { action: 'save', name: `M${i}`, items: ['GOLD'] }).store;
ok(applyAction(big, { action: 'save', name: 'one more', items: ['GOLD'] }).status === 400 && applyAction(big, { action: 'save', name: 'M2', items: ['NQ'] }).ok, 'capped, replacing still works');
const many = applyAction(s, { action: 'save', name: 'Long', items: Array.from({ length: 80 }, (_, i) => `EURUSD${i}`).concat(['GBPUSD']) });
ok(many.ok && many.store.lists[0].items.length <= MAX_ITEMS, 'item cap');
const kv = mem();
ok((await handle({ method: 'GET', role: null, kv })).status === 401, 'no session: 401');
ok((await handle({ method: 'GET', role: 'viewer', kv, on: () => false })).status === 403, 'desk login, switch off: 403');
ok((await handle({ method: 'POST', role: 'viewer', kv, on: () => true, body: { action: 'save', name: 'x', items: ['NQ'] } })).status === 403, 'desk login never writes');
ok((await handle({ method: 'POST', role: 'owner', kv, body: { action: 'save', name: 'Mine', items: ['NQ'] } })).status === 200 && kv.m.has(KEY), 'owner saves to the key');
ok((await handle({ method: 'GET', role: 'viewer', kv, on: id => id === 'tab.monitor' })).json.lists.length === 1, 'desk login reads once switched on');
kv.m.set(KEY, 'not json');
ok((await readStore(kv)).lists.length === 0, 'a corrupt store reads as empty');
console.log(`deskMonitors: ${n} checks OK`);
