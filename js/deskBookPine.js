/** A price as Pine text: enough places for any of our markets, no trailing zeros, never exponent notation. */
export const px = v => { const s = Number(v).toFixed(6).replace(/0+$/, '').replace(/\.$/, ''); return s === '-0' ? '0' : s; };
/** User text inside a Pine string literal: no double quotes, backslashes or line breaks; trimmed to `max` characters. */
export const pineText = (s, max = 140) => {
  let t = String(s ?? '').replace(/[\r\n\t]+/g, ' ').replace(/\\/g, '/').replace(/"/g, "'").replace(/\s{2,}/g, ' ').trim();
  if (t.length > max) t = `${t.slice(0, max - 1).trimEnd()}…`;
  return t;
};
const q = s => `"${s}"`;
const ymd = date => [+date.slice(0, 4), +date.slice(5, 7), +date.slice(8, 10)];
const fin = v => Number.isFinite(v) && v != null;

/** The script's preamble: the clock for the day and the two drawing helpers. */
function head(title, date, maxLines = 60) {
  const [y, m, d] = ymd(date);
  return [
    '//@version=6',
    `indicator(${q(pineText(title, 60))}, overlay = true, max_lines_count = ${maxLines}, max_labels_count = ${maxLines}, max_boxes_count = 10)`,
    `// Generated by the MacroFX desk (desk-run.html) from the ${date} morning book: ${LABEL}.`,
    '// A snapshot of one day: the lines run from London midnight to 21:00 London. Make a fresh copy each morning.',
    '// Prices are OANDA CFD mids; a futures chart (ES1!, GC1!, CL1! ...) trades at a basis to them.',
    `t0 = timestamp("Europe/London", ${y}, ${m}, ${d}, 0, 0)`,
    `t8 = timestamp("Europe/London", ${y}, ${m}, ${d}, 8, 0)`,
    `t21 = timestamp("Europe/London", ${y}, ${m}, ${d}, 21, 0)`,
    'cUp = color.new(#3fb27f, 0)', 'cDn = color.new(#c678dd, 0)', 'cInv = color.new(#e5534b, 0)', 'cTg = color.new(#e0a339, 0)', 'cOpen = color.new(color.gray, 0)',
    'lvl(p, c, st, w, txt) =>',
    '    line.new(t0, p, t21, p, xloc = xloc.bar_time, color = c, style = st, width = w)',
    '    label.new(t21, p, txt + " " + str.tostring(p, format.mintick), xloc = xloc.bar_time, style = label.style_label_left, color = color.new(c, 100), textcolor = c, size = size.small)',
    'plot(na, title = "anchor")',
  ];
}

/** The drawing statements for one card (unindented Pine lines). */
export function drawLines(inst, card) {
  const L = card?.levels, out = [], plan = cardPlan(card);
  if (!L || !fin(L.open)) return [`label.new(bar_index, close, ${q(pineText(`${inst}: the card has no forecast levels today`))}, style = label.style_label_down, color = color.new(color.gray, 70), textcolor = color.white)`];
  const tgt = plan?.target;
  out.push(`lvl(${px(L.open)}, cOpen, line.style_dotted, 1, "open")`);
  for (const [side, col] of [['up', 'cUp'], ['down', 'cDn']]) {
    for (const [k, st] of [['p50', 'line.style_solid'], ['p75', 'line.style_dashed'], ['p90', 'line.style_dotted']]) {
      const v = L[side]?.[k]; if (!fin(v)) continue;
      const isT = k === 'p50' && tgt != null && v === tgt;
      out.push(isT ? `lvl(${px(v)}, cTg, line.style_solid, 3, "first target (${side} p50)")` : `lvl(${px(v)}, ${col}, ${st}, 1, "${side} ${k}")`);
    }
  }
  if (plan?.zone) {
    const [lo, hi] = plan.zone, c = plan.dir > 0 ? 'cUp' : 'cDn';
    out.push(`box.new(t8, ${px(hi)}, t21, ${px(lo)}, xloc = xloc.bar_time, border_color = color.new(${c}, 40), bgcolor = color.new(${c}, 85), text = "entry zone ${px(lo)}${lo === hi ? '' : ` - ${px(hi)}`}", text_color = ${c}, text_size = size.small, text_halign = text.align_left, text_valign = text.align_top)`);
  }
  if (plan?.invalid != null) out.push(`lvl(${px(plan.invalid)}, cInv, line.style_solid, 2, "invalid")`);
  const lab = [`${inst} ${String(card.rating ?? '').replace('_', ' ')} · size ${card.size ?? '–'} · ${card.conviction ?? '–'} conviction`, pineText(card.why, 140), LABEL]
    .map(s => pineText(s, 160)).join('\\n');
  const top = fin(L.up?.p90) ? L.up.p90 : L.open;
  out.push(`label.new(t8, ${px(top)}, "${lab}", xloc = xloc.bar_time, style = label.style_label_down, color = color.new(color.black, 30), textcolor = color.white, size = size.small, textalign = text.align_left)`);
  return out;
}

/** One market's script. */
export function pineForCard(inst, card, { date, oandaSymbol = oandaOf(inst) } = {}) {
  const L = head(`Desk ${inst} ${date}`, date);
  if (oandaSymbol) L.splice(5, 0, `// Built for the OANDA:${String(oandaSymbol).replace('_', '')} chart.`);
  L.push('if barstate.islastconfirmedhistory', ...drawLines(inst, card).map(s => `    ${s}`));
  return L.join('\n') + '\n';
}

/**
 * The whole book in one script: it draws the card of the chart's own market (matched on syminfo.ticker or the
 * futures root), or the market picked in the settings.
 */
export function pineForBook(book, { date } = {}) {
  const cards = book?.instruments ?? book ?? {}, names = Object.keys(cards).sort();
  const L = head(`Desk book ${date}`, date);
  L.push(`mkt = input.string("auto", "Market (auto = this chart's symbol)", options = [${['auto', ...names].map(q).join(', ')}])`,
    'pick(tk, rt) =>', '    string res = "none"');
  names.forEach((n, i) => {
    const al = [...new Set(tvTickers(n))], cond = al.map(a => `tk == ${q(a)}`).concat(al.filter(a => !a.includes('!')).map(a => `rt == ${q(a)}`)).join(' or ');
    L.push(`    ${i ? 'else if' : 'if'} ${cond}`, `        res := ${q(n)}`);
  });
  L.push('    res', 'inst = mkt == "auto" ? pick(syminfo.ticker, syminfo.root) : mkt', 'if barstate.islastconfirmedhistory');
  for (const n of names) L.push(`    if inst == ${q(n)}`, ...drawLines(n, cards[n]).map(s => `        ${s}`));
  L.push('    if inst == "none"', `        label.new(bar_index, high, "No desk card matches " + syminfo.ticker + ": pick the market in the indicator's settings", style = label.style_label_down, color = color.new(color.gray, 60), textcolor = color.white)`);
  return L.join('\n') + '\n';
}

export const CSV_COLUMNS = ['date', 'inst', 'rating', 'size', 'conviction', 'zone_lo', 'zone_hi', 'invalid', 'target_p50', 'up_p50', 'up_p75', 'up_p90', 'down_p50', 'down_p75', 'down_p90', 'open', 'why'];
const cell = v => { if (v == null || (typeof v === 'number' && !Number.isFinite(v))) return ''; const s = typeof v === 'number' ? px(v) : String(v); return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };

/** One row per card in the book (FLAT cards too, with empty plan columns). */
export function csvForBook(book, { date } = {}) {
  const cards = book?.instruments ?? book ?? {}, rows = [CSV_COLUMNS.join(',')];
  for (const n of Object.keys(cards).sort()) {
    const c = cards[n], L = c?.levels ?? {}, p = cardPlan(c);
    rows.push([date ?? '', n, c?.rating, c?.size, c?.conviction, p?.zone?.[0], p?.zone?.[1], p?.invalid, p?.target, L.up?.p50, L.up?.p75, L.up?.p90, L.down?.p50, L.down?.p75, L.down?.p90, L.open, c?.why == null ? null : String(c.why).replace(/\s*[\r\n]+\s*/g, ' ')].map(cell).join(','));
  }
  return rows.join('\n') + '\n';
}
