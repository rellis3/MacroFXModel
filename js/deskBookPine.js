/**
 * The desk book as a TradingView script (owner request, 2026-11-05). For one day only, on any chart timeframe:
 *   open, up p50/p75/p90 and down p50/p75/p90 as horizontal lines (London midnight to 21:00 London);
 *   the entry zone as a box from 08:00 to 21:00 London; the invalidation as a red line; the first target (p50 on the
 *   card's side) drawn heavier; and a label with the rating, size, conviction and a short why.
 * The zone, invalidation and target come from js/tradeWatch.js cardPlan, so the chart shows exactly what the trade
 * watcher alerts on. Pine cannot fetch this site, so the prices are written into the script.
 *
 * Description, not the scored test (prereg H1). Nothing here feeds the Desk Pack or any analyst prompt.
 * Pure: no DOM, no fetch. Tested in js/deskBookPine.test.mjs.
 */
